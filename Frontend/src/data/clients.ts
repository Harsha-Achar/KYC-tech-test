export function getClientById(id: string): Client | undefined {
  return clients.find((c) => c.id === id)
}

export function getClientName(id: string): string {
  return getClientById(id)?.name ?? id
}

export function getAllClients(): Client[] {
  const base = clients
  const extras = getExtraClientNames()
    .filter((n) => !base.some((c) => c.name.toLowerCase() === n.toLowerCase()))
    .map(
      (n): Client => ({
        id: `local_${n.toLowerCase().replace(/[^a-z0-9]+/g, '_')}`,
        name: n,
        segment: '—',
        region: '—',
        industry: '—',
        apiProduct: '—',
        integrationPhase: 'Discovery',
        status: 'In Progress',
        healthScore: 75,
        openIssues: 0,
        criticalIssues: 0,
        lastActivity: new Date().toISOString(),
        supportLead: '—',
        complianceFlag: false,
        architectureRisk: 'Low',
        legacySystem: false,
        environment: 'Sandbox',
      }),
    )

  return [...base, ...extras]
}
